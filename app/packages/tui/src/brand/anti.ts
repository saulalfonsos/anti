/** Pinta unas filas de píxeles en un lienzo nuevo. */
export function paint(rows: readonly string[]) {
  const canvas = new PixelCanvas({ left: 0, top: 0, width: rows[0]!.length, height: rows.length })
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ink = INKS[Number(row[x])]
      if (ink) canvas.set(x, y, ink)
    }
  })
  return canvas
}

/** El hero de la pantalla de inicio: «Puente» en bucle; con `moving` falso (movimiento reducido), el logo quieto. */
export class PuenteScene extends FrameScene {
  static readonly columns = LOGO_WIDTH
  static readonly rows = Math.ceil(LOGO_HEIGHT / 2)
  private readonly canvases = PUENTE.map(paint)
  private readonly still = paint(STILL)

  constructor(readonly moving = true) {
    super(PUENTE_MS, PUENTE.length)
  }

  get columns() {
    return LOGO_WIDTH
  }

  get rows() {
    return Math.ceil(LOGO_HEIGHT / 2)
  }

  override advance(now: number) {
    return this.moving && super.advance(now)
  }

  draw(_width: number, _height: number, put: Put) {
    drawHalfBlocks(this.moving ? this.canvases[this.frame]! : this.still, put)
  }
}

/** La palabra quieta, para terminales estrechas. */
export class WordScene extends FrameScene {
  static readonly columns = 26
  private readonly canvas = paint(WORD)

  constructor() {
    super(1_000_000, 1)
  }

  get columns() {
    return 26
  }

  get rows() {
    return Math.ceil(WORD.length / 2)
  }

  draw(_width: number, _height: number, put: Put) {
    drawHalfBlocks(this.canvas, put)
  }
}
